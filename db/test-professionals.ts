// 0 = Sunday … 6 = Saturday.
const days = (list: number[], startTime: string, endTime: string) =>
  list.map((dayOfWeek) => ({ dayOfWeek, startTime, endTime }));
const everyDay = (startTime: string, endTime: string) =>
  days([0, 1, 2, 3, 4, 5, 6], startTime, endTime);
// Thursday to Sunday — when the clubs and the parties run.
const weekends = (startTime: string, endTime: string) =>
  days([4, 5, 6, 0], startTime, endTime);

